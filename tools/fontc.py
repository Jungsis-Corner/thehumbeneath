ROWS = 6


def glyph(c):
    rows = GLYPHS.get(c, BOX)
    rows = rows + ['...'] * (ROWS - len(rows))
    for r in rows:
        if len(r) != 3 or set(r) - set('.#'):
            sys.exit('fontc: bad glyph %r' % c)
    return [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    data = [glyph(chr(c)) for c in range(32, 127)]
    with open(sys.argv[1], 'w') as f:
        f.write('; GENERATED by tools/fontc.py - do not edit\n')
        f.write('FONT_ROWS equ %d\n' % ROWS)
        masks = []
        for v in range(8):
            m = 0
            for p in range(3):
                if v & (4 >> p):
                    m |= (3 << (14 - 2 * p)) | (3 << (6 - 2 * p))
            masks.append('$%04x' % m)
        f.write('fontexp: dc.w %s\n' % ','.join(masks))
        f.write('font:\n')
        for c, rows in zip(range(32, 127), data):
            f.write('        dc.b    %s  ; %s\n' % (','.join(map(str, rows)), repr(chr(c))))
        f.write('        even\n')
    if len(sys.argv) == 3:                    # preview of all glyphs
        from PIL import Image
        img = Image.new('RGB', (32 * 4 * 2, 3 * 7 * 2), (0, 0, 128))
        for i, rows in enumerate(data):
            cx, cy = (i % 32) * 4, (i // 32) * 7
            for y, bits in enumerate(rows):
                for p in range(3):
                    if bits & (4 >> p):
                        for dx in (0, 1):
                            for dy in (0, 1):
                                img.putpixel((2 * (cx + p) + dx, 2 * (cy + y) + dy),
                                             (255, 255, 255))
        img.resize((img.width * 2, img.height * 2)).save(sys.argv[2])
    print('fontc: %d glyphs, %d bytes' % (len(data), len(data) * ROWS + 16))


if __name__ == '__main__':
    main()
